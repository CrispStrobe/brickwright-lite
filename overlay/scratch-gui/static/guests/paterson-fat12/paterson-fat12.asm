; Owned caller: DS=SS=0, ES=0100h, FAT base ES:0600h, CHGCLS=0000:0500h.
; HLT ends a board routine test, not a DOS application.
MOV AX,0
MOV DS,AX
MOV SS,AX
MOV SP,0F000h
MOV AX,0100h
MOV ES,AX
MOV BX,0600h
MOV SI,3
MOV DX,2748
CALL PACK
CALL UNPACK
HLT
CHGCLS EQU 0500h
UNPACK:
MOV DI,SI
SHR DI,1
ADD DI,SI
MOV DI,ES:[DI+BX]
TEST SI,1
JZ HAVCLUS
SHR DI,1
SHR DI,1
SHR DI,1
SHR DI,1
HAVCLUS:
AND DI,0FFFH
RET
PACK:
MOV BYTE PTR [CHGCLS],1
PUSH SI
MOV DI,SI
SHR SI,1
ADD SI,BX
ADD SI,DI
SHR DI,1
MOV DI,ES:[SI]
JNC ALIGNED
SHL DX,1
SHL DX,1
SHL DX,1
SHL DX,1
AND DI,0FH
JMP SHORT PACKIN
ALIGNED:
AND DI,0F000H
PACKIN:
OR DI,DX
MOV ES:[SI],DI
POP SI
RET
