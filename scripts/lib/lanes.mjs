/**
 * Lane claims, one file per claim: lanes/<YYYY-MM-DD>-<slug>.md.
 *
 * Until 2026-10-20 every claim was a row prepended to LANES.md, so each merge
 * made every other open PR conflict. Now a claim is its own file and LANES.md
 * is a stable header. This module is the one reader: it lists the claims and
 * judges each file's shape.
 */
import {existsSync, readdirSync, readFileSync} from 'node:fs';
import path from 'node:path';

export const LANES_DIR = 'lanes';
export const CLAIM_NAME = /^(\d{4})-(\d\d)-(\d\d)-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$/;
/** Files in lanes/ that are not claims. */
export const NON_CLAIMS = new Set(['PROTOCOL.md', 'MIGRATION-2026-10-20.tsv']);
const LOCAL_PATH = /(?:^|[\s`(="'])\/(?:mnt|home|Users|tmp\/claude)\//;

const validDate = (y, m, d) => {
    const t = new Date(Date.UTC(+y, +m - 1, +d));
    return t.getUTCFullYear() === +y && t.getUTCMonth() === +m - 1 && t.getUTCDate() === +d;
};

/** Problems with one claim file (name and text); [] when it is well formed. */
export const claimProblems = (name, text) => {
    const out = [];
    const m = name.match(CLAIM_NAME);
    if (!m) out.push(`${LANES_DIR}/${name}: a claim is named <YYYY-MM-DD>-<lower-case-slug>.md`);
    else if (!validDate(m[1], m[2], m[3])) out.push(`${LANES_DIR}/${name}: ${m[1]}-${m[2]}-${m[3]} is not a date`);
    if (!text.trim()) out.push(`${LANES_DIR}/${name}: empty claim`);
    text.split('\n').forEach((line, i) => {
        if (LOCAL_PATH.test(line)) out.push(`${LANES_DIR}/${name}:${i + 1}: a local machine path in public text`);
    });
    return out;
};

/** Every claim under root/lanes, oldest first: {file, date, slug, title, text}. */
export const listClaims = root => {
    const dir = path.join(root, LANES_DIR);
    if (!existsSync(dir)) return [];
    return readdirSync(dir).filter(f => f.endsWith('.md') && !NON_CLAIMS.has(f)).sort().map(f => {
        const text = readFileSync(path.join(dir, f), 'utf8');
        const m = f.match(CLAIM_NAME);
        const first = text.split('\n').find(l => l.trim()) || '';
        const title = (/^#+ /.test(first) ? first.replace(/^#+ /, '')
            : /^\|/.test(first) ? first.split('|')[1] : first).trim();
        return {file: `${LANES_DIR}/${f}`, date: m ? `${m[1]}-${m[2]}-${m[3]}` : null, slug: m ? m[4] : null, title, text};
    });
};

/** Problems across the whole directory. */
export const lanesProblems = root => {
    const dir = path.join(root, LANES_DIR);
    if (!existsSync(dir)) return [`no ${LANES_DIR}/ directory`];
    const out = [];
    for (const f of readdirSync(dir)) {
        if (NON_CLAIMS.has(f)) continue;
        out.push(...claimProblems(f, readFileSync(path.join(dir, f), 'utf8')));
    }
    return out;
};

/** A deterministic Markdown index, newest first. Printed, never committed. */
export const lanesIndex = claims => ['# Lane claims (generated by scripts/gen-lanes-index.mjs)', '',
    `${claims.length} claim(s), newest first.`, '',
    ...[...claims].reverse().map(c => `- ${c.date} [${c.title.replace(/[[\]]/g, '').slice(0, 120)}](${c.file})`)].join('\n') + '\n';
