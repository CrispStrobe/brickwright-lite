import {createHash} from 'node:crypto';
export function adaptCascadeProgram(bytes){
 const raw=Buffer.isBuffer(bytes)?bytes:Buffer.from(bytes);
 if(createHash('sha256').update(raw).digest('hex')!=='a5a213afffda8c87a78ed1daca4b102e94242edd8f08b1eac2c407cd11ab16ee')throw Error('Cascade source differs from the reviewed program');
 const source=raw.toString('utf8'),old='set stage to 1\n  set targetA to 90\n  set speedA to 180';
 if(!source.includes(old))throw Error('Missing exact outward pulse');
 return '# App pulse revision 3: slow outward placement, fast return; all original guards and observation limits retained.\n'+source
  .replace(old,'set stage to 1\n  set targetA to 90\n  set speedA to 30')
  .replace('# Main leg speeds: 180, 180 degrees/s.','# Main leg speeds: 30, 180 degrees/s.')
  .replace('# Generated by build/build_program.py from the frozen experiment config.','# Adapted from the frozen source program; original inputs remain in the source fixture.')
  .replace('# Config SHA-256:','# Original source config SHA-256:')
  .replace('# Main model SHA-256:','# Original source main model SHA-256:')
  .replace('# Control model SHA-256:','# Original source control model SHA-256:');
}
