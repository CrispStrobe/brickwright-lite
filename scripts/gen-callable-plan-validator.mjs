// The native declaration validator is generated from the frontend schema;
// current procedure bodies stay outside this inert metadata authority.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const input=new URL('../overlay/scratch-gui/src/lib/bw-makecode/callable-lexical-plan.js',import.meta.url);
const output=new URL('../overlay/scratch-vm/src/extensions/crispstrobe/arcade/callable-lexical-plan.generated.js',import.meta.url);
const source=readFileSync(input,'utf8');
const start=source.indexOf('// Inert source-derived'),end=source.indexOf('\nexport function createCallableLexicalPlan');
if(start<0 || end<start || !source.slice(start,end).includes('export function validateCallableLexicalPlan(plan)'))throw new Error('Callable schema generation boundaries changed');
const result='// Generated by scripts/gen-callable-plan-validator.mjs; do not edit.\n'+
    source.slice(start,end).replace('export function validateCallableLexicalPlan','function validateCallableLexicalPlan')+
    '\nmodule.exports = {validateCallableLexicalPlan};\n';
if(process.argv.includes('--check')){
    if(readFileSync(output,'utf8')!==result)throw new Error('Native callable schema copy differs from canonical frontend schema');
}else writeFileSync(output,result);
console.log('Callable inert schema native copy matches',fileURLToPath(output).split('/overlay/')[1]);
