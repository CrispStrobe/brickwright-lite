#!/usr/bin/env node
/**
 * Snapshot bw-board's ORACLE CENSUS at the sha lite pins, so the matrix's
 * `needs` can be joined to something measured rather than to a name.
 *
 * Plan task T6 (docs/LANGUAGE-DEVICE-MATRIX-PLAN.md). Every `tier` in
 * `lib/bw-matrix/capabilities.js` rests on external oracles named in `needs`;
 * bw-board's `scripts/oracle-census.mjs --snapshot` is the one place that says,
 * per oracle, whether it is present, whether CI runs it (standing) or not
 * (recorded), and which gates read it. This script runs THAT tree's generator
 * -- the tree at lite's pin, not master -- and writes the result to
 * docs/generated/bw-board-census.json.
 *
 *   node scripts/gen-bw-board-census.mjs --dir /path/to/bw-board
 *   node scripts/gen-bw-board-census.mjs --dir /path/to/bw-board --check
 *
 * Refusals, by name:
 *   - the checkout's HEAD is not the sha vendor-pins.json pins (a snapshot of
 *     some other tree would describe oracles the vendored code never saw);
 *   - the checkout's oracle-census.mjs has no `--snapshot` flag (added in
 *     bw-board a9fea52; an older pin cannot produce a snapshot and must say so
 *     rather than hand back an empty file).
 *
 * What is stable and what is not: `present` and `via` describe the box the
 * census was read on (a developer machine has vectors under $HOME; CI does
 * not). `ciAvailable`, `ci`, `kind`, `gates` and `what` are facts about the
 * bw-board tree itself. `--check` therefore compares the STABLE fields and the
 * source sha, and says so; a box with different fixtures installed does not
 * make the snapshot stale, a moved pin or a changed census does.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';

const root = path.resolve(import.meta.dirname, '..');
export const output = path.join(root, 'docs/generated/bw-board-census.json');
const rel = p => path.relative(root, p).replaceAll(path.sep, '/');

export const STABLE_FIELDS = Object.freeze(['id', 'kind', 'ciAvailable', 'ci', 'gates', 'what']);

const pinnedSha = () => JSON.parse(fs.readFileSync(path.join(root, 'vendor-pins.json'), 'utf8'))['bw-board'];
const headOf = dir => execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], {encoding: 'utf8'}).trim();

/**
 * Refuse, by name, a census script that cannot write a snapshot.
 * @param {string} census path to a checkout's scripts/oracle-census.mjs
 */
export function requireSnapshotFlag (census) {
    if (!fs.existsSync(census)) {
        throw new Error(`REFUSED: ${path.dirname(path.dirname(census))} has no scripts/oracle-census.mjs -- not a bw-board checkout, or one older than the census itself`);
    }
    if (!fs.readFileSync(census, 'utf8').includes('--snapshot')) {
        throw new Error('REFUSED: oracle-census.mjs in this tree has no --snapshot flag. It was added in bw-board a9fea52; '
            + 'a checkout pinned before that cannot produce a snapshot. Pin bw-board >= a9fea52.');
    }
}

/**
 * Run the pinned tree's census generator and return the parsed snapshot.
 * @param {string} dir a bw-board checkout
 * @returns {object} the census document as bw-board wrote it
 */
export function build (dir) {
    const pin = pinnedSha();
    const head = headOf(dir);
    if (head !== pin) {
        throw new Error(`REFUSED: ${dir} is at ${head.slice(0, 9)} but vendor-pins.json pins bw-board `
            + `${pin.slice(0, 9)}. The census must describe the tree the vendored code came from; `
            + `check out ${pin.slice(0, 9)} there (or move the pin first, deliberately).`);
    }
    const census = path.join(dir, 'scripts/oracle-census.mjs');
    requireSnapshotFlag(census);
    const tmp = path.join(os.tmpdir(), `bw-board-census-${process.pid}.json`);
    try {
        execFileSync(process.execPath, [census, '--snapshot', tmp], {cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe']});
        const doc = JSON.parse(fs.readFileSync(tmp, 'utf8'));
        if (!doc || !Array.isArray(doc.rows) || !doc.source || doc.source.sha !== head) {
            throw new Error(`REFUSED: the snapshot from ${rel(census)} does not have the shape {source:{sha}, rows[]} for ${head.slice(0, 9)}`);
        }
        doc.lite = {
            how: 'generated by scripts/gen-bw-board-census.mjs, which runs the PINNED bw-board tree\'s '
                + 'scripts/oracle-census.mjs --snapshot; refresh with `node scripts/gen-bw-board-census.mjs --dir <bw-board>`',
            stable: [...STABLE_FIELDS],
            note: '`present` and `via` are the box the census was read on; `ciAvailable`/`ci` are the standing facts '
                + 'the matrix joins to. A row with kind "service" is reachability, never probed: present is false by design.'
        };
        return doc;
    } finally {
        fs.rmSync(tmp, {force: true});
    }
}

const stableView = doc => ({
    sha: doc.source.sha,
    rows: doc.rows.map(r => Object.fromEntries(STABLE_FIELDS.map(f => [f, r[f]])))
});

/**
 * Compare the committed snapshot's stable fields with a fresh run.
 * @param {string} dir a bw-board checkout at the pinned sha
 * @throws when the committed file is missing, or its stable fields differ
 */
export function checkAgainst (dir) {
    if (!fs.existsSync(output)) throw new Error(`${rel(output)} is missing; run: node scripts/gen-bw-board-census.mjs --dir ${dir}`);
    const committed = JSON.parse(fs.readFileSync(output, 'utf8'));
    const fresh = build(dir);
    const a = JSON.stringify(stableView(committed));
    const b = JSON.stringify(stableView(fresh));
    if (a !== b) {
        throw new Error(`${rel(output)} is STALE against ${dir} (bw-board ${fresh.source.sha.slice(0, 9)}): the stable `
            + `fields (${STABLE_FIELDS.join(', ')}) or the source sha differ; run: node scripts/gen-bw-board-census.mjs --dir ${dir}`);
    }
}

const main = () => {
    const args = process.argv.slice(2);
    const dirIdx = args.indexOf('--dir');
    const dir = dirIdx !== -1 ? path.resolve(args[dirIdx + 1] || '') : null;
    if (!dir) { console.error('usage: gen-bw-board-census.mjs --dir <bw-board checkout> [--check]'); process.exit(2); }
    if (args.includes('--check')) {
        checkAgainst(dir);
        console.log(`${rel(output)} is current against ${dir}`);
        return;
    }
    const doc = build(dir);
    fs.writeFileSync(output, `${JSON.stringify(doc, null, 2)}\n`);
    console.log(`wrote ${rel(output)} (${doc.rows.length} rows, bw-board ${doc.source.sha.slice(0, 9)})`);
};

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
    try { main(); } catch (e) { console.error(e.message); process.exit(1); }
}
