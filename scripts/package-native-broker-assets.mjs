import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const paths = Object.freeze({
    host: 'overlay/scratch-vm/src/extension-support/native-broker-worker-host.js',
    worker: 'overlay/scratch-vm/src/extension-support/native-broker-extension-worker.js',
    manifest: 'overlay/scratch-gui/static/native-broker/proof-pins/manifest.json'
});
const output = 'overlay/scratch-gui/static/native-broker';
const banner = '// AUTO-GENERATED by scripts/package-native-broker-assets.mjs. DO NOT EDIT.\n';

const moduleBody = source => source.replace(/^\uFEFF/u, '');
export const generateNativeBrokerAssets = inputs => {
    for (const name of Object.keys(paths)) if (typeof inputs[name] !== 'string') throw new TypeError(`missing ${name}`);
    if (typeof inputs.proof !== 'string') throw new TypeError('missing proof');
    const manifest = JSON.parse(inputs.manifest);
    if (manifest.schema !== 1 || !manifest.source || !manifest.aliases) throw new Error('invalid packaged pin manifest');
    const proofBytes = new TextEncoder().encode(inputs.proof);
    const proofDigest = createHash('sha256').update(proofBytes).digest('hex');
    if (manifest.source.bytes !== proofBytes.byteLength || manifest.source.digest !== proofDigest) {
        throw new Error('packaged proof bytes do not match manifest');
    }
    const hostSource = moduleBody(inputs.host).replace(
        "require('../../../scratch-gui/static/native-broker/proof-pins/manifest.json')", 'packagedManifest');
    if (hostSource === inputs.host) throw new Error('worker host manifest import changed');
    const worker = `${banner}(()=>{'use strict';const nativePost=globalThis.postMessage.bind(globalThis);` +
        `const nativeAdd=globalThis.addEventListener.bind(globalThis);const nativeClose=globalThis.close.bind(globalThis);` +
        `const nativeImport=globalThis.importScripts.bind(globalThis);const NativeBlob=globalThis.Blob;` +
        `const nativeCreate=globalThis.URL.createObjectURL.bind(globalThis.URL);const nativeRevoke=globalThis.URL.revokeObjectURL.bind(globalThis.URL);` +
        `const module={exports:{}};${moduleBody(inputs.worker)}\n` +
        `const evaluate=source=>{const url=nativeCreate(new NativeBlob([source],{type:'text/javascript'}));try{nativeImport(url);}finally{nativeRevoke(url);}};` +
        `module.exports.installNativeBrokerExtensionWorker({port:{postMessage:nativePost,addEventListener:nativeAdd,close:nativeClose},realm:globalThis,evaluate});})();\n`;
    const host = `${banner}(()=>{'use strict';\n` +
        `const packagedManifest=${JSON.stringify(manifest)};\n` +
        `const packagedProof=${JSON.stringify(inputs.proof)};const packagedWorker=${JSON.stringify(worker)};\n` +
        `const hostModule=(()=>{const module={exports:{}};${hostSource}\nreturn module.exports;})();\n` +
        `const loadAsset=async(asset,{signal})=>{if(signal.aborted||asset!==packagedManifest.source.asset)throw new Error('asset unavailable');return new TextEncoder().encode(packagedProof);};\n` +
        `const createWorker=()=>{const url=URL.createObjectURL(new Blob([packagedWorker],{type:'text/javascript'}));try{return new Worker(url);}finally{URL.revokeObjectURL(url);}};\n` +
        `const host=hostModule.createNativeBrokerWorkerHost({createWorker,loadAsset});\n` +
        `const createProtocol=(owner,_session,NativeBrokerProtocol)=>new NativeBrokerProtocol({owner,resolvePin:host.resolvePin,startWorker:host.startWorker,callWorker:host.callWorker,revokeWorker:host.revokeWorker,terminateWorker:host.terminateWorker});\n` +
        `if(typeof globalThis.__brickwrightInstallBrokerHost!=='function')throw new TypeError('Broker bootstrap unavailable');globalThis.__brickwrightInstallBrokerHost(createProtocol);\n})();\n`;
    return Object.freeze({host, worker});
};

const readInputs = async () => {
    const inputs = Object.fromEntries(await Promise.all(Object.entries(paths).map(async ([name, relative]) =>
        [name, await readFile(path.join(root, relative), 'utf8')])));
    const manifest = JSON.parse(inputs.manifest);
    inputs.proof = await readFile(path.join(root, output, 'proof-pins', manifest.source.asset), 'utf8');
    return inputs;
};
const main = async () => {
    const generated = generateNativeBrokerAssets(await readInputs());
    const files = {host: path.join(root, output, 'native-broker-host.js'),
        worker: path.join(root, output, 'native-broker-extension-worker.js')};
    if (process.argv.includes('--check')) {
        const current = await Promise.all(Object.values(files).map(file => readFile(file, 'utf8').catch(() => '')));
        if (current[0] !== generated.host || current[1] !== generated.worker) {
            throw new Error('packaged native broker assets are stale; run npm run package:broker-assets');
        }
        console.log('native broker host and worker assets are current'); return;
    }
    await mkdir(path.join(root, output), {recursive: true});
    await Promise.all([writeFile(files.host, generated.host), writeFile(files.worker, generated.worker)]);
    console.log('wrote deterministic native broker host and worker assets');
};
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
