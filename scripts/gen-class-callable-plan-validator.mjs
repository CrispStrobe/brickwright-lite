import {readFileSync,writeFileSync} from 'node:fs';
const input=new URL('../overlay/scratch-gui/src/lib/bw-makecode/class-callable-plan.js',import.meta.url);
const output=new URL('../overlay/scratch-vm/src/extensions/crispstrobe/arcade/class-callable-plan.generated.js',import.meta.url);
const source=readFileSync(input,'utf8');
if(!source.includes('export function validateClassCallablePlan(plan)')||/\bimport\s/.test(source))throw new Error('Class callable schema generation boundary changed');
const boundary=source.indexOf('\n// Build only after');
if(boundary<0)throw new Error('Class callable schema validator boundary changed');
const result='// Generated by scripts/gen-class-callable-plan-validator.mjs; do not edit.\n'+
    source.slice(0,boundary).replace('export function validateClassCallablePlan','function validateClassCallablePlan')+
    '\nmodule.exports = {validateClassCallablePlan};\n';
if(process.argv.includes('--check')) {
    if(readFileSync(output,'utf8')!==result)throw new Error('Native class callable schema differs from the frontend validator');
}else writeFileSync(output,result);
console.log('Class callable v2 native schema matches its frontend source');
