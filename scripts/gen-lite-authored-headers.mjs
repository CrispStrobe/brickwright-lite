/**
 * Mark the files lite AUTHORED inside a vendored root, in the files themselves.
 *
 * WHY THESE AND NOT EVERY VENDORED FILE. A header on a vendored file makes it
 * differ from upstream, and test/vendor-identity.test.mjs asserts BYTE equality
 * against upstream at the pin -- so marking the 325 commentable vendored files
 * would red that gate on all of them, and keeping both would mean comparing
 * "identical after stripping a known header", which trades the strongest claim
 * in the vendor lane for a comment. These eleven are the opposite case: upstream
 * has NO counterpart, so a marker costs nothing and reds nothing.
 *
 * They are also the files that most need it. Upstream cannot restore them, no
 * upstream review ever sees them, and a sync deleted one of them
 * (intro-doc.jsx) on 2026-09-08 because a hardcoded keep-list was missing an
 * entry -- leaving a vendored component importing five symbols from a file that
 * no longer existed.
 *
 * GENERATED, NOT HAND-WRITTEN, so the marker cannot drift from the manifest that
 * declares it: the block is delimited, rewritten in place, and
 * test/lite-authored-headers.test.mjs asserts every file's block is exactly what
 * this script would write. The manifest stays authoritative; the header is a
 * mirror that must agree with it.
 *
 *   node scripts/gen-lite-authored-headers.mjs           rewrite the blocks
 *   node scripts/gen-lite-authored-headers.mjs --check   exit 1 if any is stale
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.join(here, '..');

// Each manifest and the root it declares. Read, never re-derived.
export const SOURCES = [
    { doc: 'docs/VENDOR-DIVERGENCE-I8086-MACHINE.md', root: 'overlay/scratch-gui/src/lib/bw-board' },
    { doc: 'docs/VENDOR-DIVERGENCE-BW-CIRCUIT-UI.md', root: 'overlay/scratch-gui/src/lib/bw-circuit-ui' },
];

// NOT MARKED, each for a reason rather than because the loop skipped them.
// LICENSE is a licence text: prepending anything to it alters a legal notice,
// and its own first line already says what it is. .vendor-manifest.json is
// generated by the sync and is JSON, which carries no comment at all -- and a
// marker there would be rewritten by the next sync anyway.
export const NEVER_MARK = new Set(['LICENSE', '.vendor-manifest.json']);

export const BEGIN = '// --- lite-authored marker: generated by scripts/gen-lite-authored-headers.mjs ---';
export const END = '// --- end lite-authored marker ---';

const wrap = (text, width = 76) => {
    const out = [];
    let line = '';
    for (const word of text.split(/\s+/)) {
        if (line && (line + ' ' + word).length > width) { out.push(line); line = word; }
        else line = line ? `${line} ${word}` : word;
    }
    if (line) out.push(line);
    return out;
};

export const blockFor = (file, entry, doc) => {
    const lines = [BEGIN,
        `// ${file} is LITE-AUTHORED and lives inside a VENDORED root.`,
        '//',
        '// Upstream has no copy of this file, so a sync cannot restore it and no',
        '// upstream review will ever see it. It is declared in',
        `// ${doc}`,
        '// -- edit that entry, not this block, which is generated.',
        '//',
        '// WHY IT LIVES HERE:'];
    for (const l of wrap(entry.reason)) lines.push(`// ${l}`);
    if (entry.importedBy?.length) lines.push('//', `// Imported by: ${entry.importedBy.join(', ')}`);
    lines.push(END);
    return lines.join('\n');
};

export const declared = async () => {
    const out = [];
    for (const { doc, root } of SOURCES) {
        const md = await readFile(path.join(ROOT, doc), 'utf8');
        const m = md.match(/```json\n([\s\S]*?)\n```/);
        if (!m) continue;
        const files = JSON.parse(m[1]).liteAuthored?.files ?? {};
        for (const [file, entry] of Object.entries(files)) {
            if (NEVER_MARK.has(path.basename(file))) continue;
            out.push({ file, entry, doc, rel: path.join(root, file) });
        }
    }
    return out;
};

// Replace an existing block, or prepend a new one. Idempotent by construction:
// the block is delimited, so a second run rewrites the same span.
export const applied = (src, block) => {
    const i = src.indexOf(BEGIN);
    if (i === -1) return `${block}\n\n${src}`;
    const j = src.indexOf(END, i);
    return src.slice(0, i) + block + src.slice(j + END.length);
};

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
    const check = process.argv.includes('--check');
    const stale = [];
    for (const { file, entry, doc, rel } of await declared()) {
        const p = path.join(ROOT, rel);
        const src = await readFile(p, 'utf8');
        const next = applied(src, blockFor(file, entry, doc));
        if (next === src) { console.log(`  ok    ${rel}`); continue; }
        stale.push(rel);
        if (check) { console.log(`  STALE ${rel}`); continue; }
        await writeFile(p, next);
        console.log(`  wrote ${rel}`);
    }
    if (check && stale.length) {
        console.error(`\n${stale.length} marker(s) do not match the manifest — run: node scripts/gen-lite-authored-headers.mjs`);
        process.exit(1);
    }
    console.log(check ? '\nmarkers agree with the manifests.' : `\n${stale.length} marker(s) written.`);
}
