#!/usr/bin/env node
// Reproducible generation of approved MIT source/recipe assets and isolated
// engine copy. Never changes the production bw-board vendor pin.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,dirname,join} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';

const app=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const upstream=process.argv[2];
const revision=process.argv[3];
if(!upstream || !/^[a-f0-9]{40}$/.test(revision || '')) throw new Error('usage: preserve-paterson-lab.mjs <bw-board checkout> <40-hex revision>');
const board=resolve(upstream);
const git=(...args)=>execFileSync('git',['-C',board,...args]);
if(git('rev-parse','HEAD').toString().trim()!==revision) throw new Error('upstream checkout must be at requested revision');
git('diff','--quiet',revision,'--','src','scripts/lib','test/fixtures/paterson');
const lib=join(app,'overlay/scratch-gui/src/lib/bw-286-lab');
const asset=join(app,'overlay/scratch-gui/static/guests/paterson-fat12');
const source=JSON.parse(readFileSync(join(lib,'engine/SOURCE.json')));
const outputs=new Map();
const write=(path,bytes)=>outputs.set(path,bytes);
source.revision=revision;
for(const entry of source.files) {
    const path=entry.file==='LICENSE'?'LICENSE':`src/${entry.file}`;
    const bytes=git('show',`${revision}:${path}`);
    entry.gitBlob=git('rev-parse',`${revision}:${path}`).toString().trim();
    write(join(lib,'engine',entry.file),bytes);
}
write(join(lib,'engine/SOURCE.json'),JSON.stringify(source,null,2)+'\n');
const {fat12Assembly,fat12Program,patersonSource}=await import(pathToFileURL(join(board,'scripts/lib/paterson-routines.mjs')));
const {createHarrisBootROM}=await import(pathToFileURL(join(board,'src/experimental/harris-boot-rom.js')));
const {createHarrisCircuitDocument}=await import(pathToFileURL(join(board,'src/experimental/harris-circuit-session.js')));
const {registerBusMemory}=await import(pathToFileURL(join(board,'src/devices/bus-memory.js')));
registerBusMemory();
const options={pack:true,cluster:3,value:0xabc};
const bytes=fat12Program(options), original=patersonSource();
const rom=createHarrisBootROM(); rom.fill(255,0x100,0xfff0); rom.set(bytes,0x100);
const recipe=createHarrisCircuitDocument({enabled:true,rom,romLowAlias:true});
write(join(asset,'original-chkdsk.asm'),readFileSync(join(board,'test/fixtures/paterson/CHKDSK_1981-06-15.ASM')));
write(join(asset,'LICENSE'),readFileSync(join(board,'test/fixtures/paterson/LICENSE')));
write(join(asset,'paterson-fat12.asm'),fat12Assembly(options)+'\n');
write(join(asset,'paterson-fat12.board.json'),JSON.stringify(recipe)+'\n');
write(join(lib,'paterson-fat12.js'),`// Generated by scripts/preserve-paterson-lab.mjs. Adapted Microsoft/Paterson code, MIT.\n// Original, adaptations and licence: static/guests/paterson-fat12/. Routine test, not DOS.\nexport const PATERSON_FAT12_BYTES = Object.freeze(${JSON.stringify([...bytes])});\n`);
const sha=path=>createHash('sha256').update(outputs.get(join(asset,path))).digest('hex');
write(join(asset,'SOURCE.json'),JSON.stringify({
    ...original.manifest,localPath:'original-chkdsk.asm',engineRevision:revision,
    generated:['paterson-fat12.asm','paterson-fat12.board.json'].map(path=>({path,sha256:sha(path)})),
    runtimeBytesSha256:createHash('sha256').update(bytes).digest('hex'),
    acceptance:'PACK/UNPACK routine only; DI=0xABC, CHGCLS at 0000:0500 is 1; no DOS/kernel boot'
},null,2)+'\n');
for(const [path,bytes] of outputs) {mkdirSync(dirname(path),{recursive:true});writeFileSync(path,bytes);}
console.log(JSON.stringify({engineRevision:revision,programBytes:bytes.length,assetDirectory:asset}));
