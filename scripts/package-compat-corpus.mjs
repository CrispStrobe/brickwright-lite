#!/usr/bin/env node
/** Stage the exact compatibility corpus for a separate private Git repository. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2] || '/mnt/storage/brickwright-corpora';
const destination = process.argv[3];
if (!destination) {
    console.error('usage: node scripts/package-compat-corpus.mjs SOURCE-CORPUS-DIR DESTINATION');
    process.exit(2);
}
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const git = (...args) => execFileSync('git', args, {cwd: root, encoding: 'utf8'}).trim();
const upstream = {
    'turbowarp-extensions': 'a1e8e143a47738a95217ebd77c8875ae3e468752',
    'turbowarp-scratch-vm': 'c4823421cb7c17d8d8a89878851ce1668c26a21f'
};
const manifest = {schema: 'brickwright/compat-corpus/v1', generatedAt: new Date().toISOString(),
    sourceCommit: git('rev-parse', 'HEAD'), entries: []};
function put (from, to, provenance, license) {
    const bytes = fs.readFileSync(from);
    const dest = path.join(destination, to);
    fs.mkdirSync(path.dirname(dest), {recursive: true});
    fs.writeFileSync(dest, bytes);
    manifest.entries.push({file: to.replaceAll(path.sep, '/'), sha256: sha256(bytes),
        bytes: bytes.length, source: provenance, license});
}
const collected = path.join(source, 'collected');
const index = JSON.parse(fs.readFileSync(path.join(collected, 'manifest.json'), 'utf8'));
for (const entry of index.entries) {
    put(path.join(collected, entry.file), path.join('makecode', entry.file), entry.source, entry.license);
}
for (const [repo, subdir, license] of [
    ['turbowarp-extensions', 'samples', 'CC-BY-4.0'],
    ['turbowarp-scratch-vm', 'test', 'MPL-2.0']
]) {
    const base = path.join(source, repo, subdir);
    function walk (dir) {
        for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
            const from = path.join(dir, entry.name);
            if (entry.isDirectory()) walk(from);
            else if (entry.name.endsWith('.sb3')) {
                const rel = path.relative(base, from).replaceAll(path.sep, '/');
                put(from, path.join(repo, rel),
                    `https://github.com/TurboWarp/${repo === 'turbowarp-extensions' ? 'extensions' : 'scratch-vm'}/blob/${upstream[repo]}/${subdir}/${rel}`,
                    license);
            }
        }
    }
    walk(base);
}
const bwFiles = git('ls-files', '*.bw').split('\n').filter(Boolean);
for (const rel of bwFiles) {
    put(path.join(root, rel), path.join('brickwright', rel),
        `https://github.com/CrispStrobe/brickwright-lite/blob/${manifest.sourceCommit}/${rel}`, 'BSD-3-Clause');
}
manifest.entries.sort((a, b) => a.file.localeCompare(b.file));
manifest.count = manifest.entries.length;
manifest.counts = Object.fromEntries(['makecode', 'turbowarp-extensions', 'turbowarp-scratch-vm', 'brickwright']
    .map(group => [group, manifest.entries.filter(e => e.file.startsWith(`${group}/`)).length]));
fs.writeFileSync(path.join(destination, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
for (const [from, to] of [
    [path.join(source, 'pxt-arcade', 'LICENSE'), 'licenses/pxt-arcade-MIT.txt'],
    [path.join(source, 'turbowarp-extensions', 'licenses', 'CC-BY-4.0.txt'), 'licenses/turbowarp-samples-CC-BY-4.0.txt'],
    [path.join(source, 'turbowarp-scratch-vm', 'LICENSE'), 'licenses/turbowarp-vm-MPL-2.0.txt'],
    [path.join(root, 'LICENSE'), 'licenses/brickwright-BSD-3-Clause.txt']
]) {
    fs.mkdirSync(path.join(destination, path.dirname(to)), {recursive: true});
    fs.copyFileSync(from, path.join(destination, to));
}
fs.writeFileSync(path.join(destination, 'README.md'), `# Brickwright compatibility corpus

Private test corpus of ${manifest.count} programs and projects. This repository holds test inputs,
not the upstream extension implementation code. The SHA-256, exact upstream revision,
source URL, and license for every file are in [manifest.json](manifest.json).

| group | files | source |
|---|---:|---|
| MakeCode TypeScript | ${manifest.counts.makecode} | pinned pxt-microbit 9.1.1 and pxt-arcade docs |
| TurboWarp gallery .sb3 | ${manifest.counts['turbowarp-extensions']} | extensions sample projects |
| TurboWarp VM .sb3 | ${manifest.counts['turbowarp-scratch-vm']} | VM test fixtures, including deliberately damaged files |
| Brickwright .bw | ${manifest.counts.brickwright} | shipped Brickwright examples |

The full upstream source trees are not copied here. Source code and project assets retain
their respective upstream licenses; see the license copies in \`licenses/\` and the
manifest. Conversion reports are generated by the Brickwright Lite audit scripts.
`);
console.log(JSON.stringify({destination, count: manifest.count, counts: manifest.counts}));
