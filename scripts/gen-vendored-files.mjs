/**
 * The index that answers "is this file vendored, and from where" for EVERY
 * vendored file, without touching one byte of them.
 *
 * The companion to scripts/gen-lite-authored-headers.mjs, and deliberately the
 * second half rather than the first. A marker inside a VENDORED file would make
 * it differ from upstream, and test/vendor-identity.test.mjs asserts byte
 * equality against upstream at the pin -- so the 325 commentable vendored files
 * cannot carry one without weakening that gate to "identical after stripping a
 * known header". This index reaches all of them instead, at the cost that a
 * reader who opens the file sees nothing and has to know to look here. That
 * weakness is real; it is why the eleven files that CAN be marked are marked.
 *
 * WHAT IT IS NOT. It is not a second opinion about divergence. The divergence
 * manifests stay authoritative and this index MIRRORS them -- a file is flagged
 * here because a manifest declares it, and the flag is regenerated from that
 * manifest every time. Nothing here is hand-maintained.
 *
 *   node scripts/gen-vendored-files.mjs           rewrite the index
 *   node scripts/gen-vendored-files.mjs --check   exit 1 if it is stale
 */
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.join(here, '..');
export const OUT = 'docs/generated/VENDORED-FILES.md';

export const TREES = [
    { repo: 'bw-board', root: 'overlay/scratch-gui/src/lib/bw-board',
      doc: 'docs/VENDOR-DIVERGENCE-I8086-MACHINE.md' },
    { repo: 'bw-circuit-ui', root: 'overlay/scratch-gui/src/lib/bw-circuit-ui',
      doc: 'docs/VENDOR-DIVERGENCE-BW-CIRCUIT-UI.md' },
];

// Tracked files only, from git rather than the filesystem: an untracked file in
// a vendored root is not vendored, it is somebody's scratch copy, and listing it
// would say the opposite.
const tracked = (dir) => execFileSync('git', ['ls-tree', '-r', '--name-only', 'HEAD', dir],
    { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(Boolean).sort();

const manifestOf = async (doc) => {
    const md = await readFile(path.join(ROOT, doc), 'utf8');
    const m = md.match(/```json\n([\s\S]*?)\n```/);
    return m ? JSON.parse(m[1]) : {};
};

export const render = async () => {
    const pins = JSON.parse(await readFile(path.join(ROOT, 'vendor-pins.json'), 'utf8'));
    const out = [
        '# Vendored files',
        '',
        'GENERATED by `scripts/gen-vendored-files.mjs`. Do not edit: the divergence',
        'manifests and `vendor-pins.json` are the authority and this file mirrors them.',
        '',
        'Every file below is copied from an upstream repository at the recorded pin. An',
        'edit here is lost by the next sync unless the file is DECLARED in that tree\'s',
        'divergence manifest -- send the change upstream first, then re-pin, which is the',
        'rule `test/vendor-identity.test.mjs` enforces.',
        '',
        'Files marked `[declared]` deliberately differ from upstream and the manifest says',
        'why. Files marked `[lite]` were written by lite and have NO upstream counterpart:',
        'a sync cannot restore them, and they carry the same warning in their own header.',
        '',
    ];
    for (const { repo, root, doc } of TREES) {
        const spec = await manifestOf(doc);
        const declared = new Set([...Object.keys(spec.files || {}), ...(spec.lineLevelOnly?.files ?? [])]);
        const lite = new Set(Object.keys(spec.liteAuthored?.files ?? {}));
        const files = tracked(root);
        out.push(`## ${repo}`, '',
            `Pinned at \`${pins[repo]}\`. Manifest: \`${doc}\`.`, '',
            `${files.length} tracked file(s): ${files.length - declared.size - lite.size} plain, ` +
            `${declared.size} declared-divergent, ${lite.size} lite-authored.`, '');
        for (const f of files) {
            const rel = f.slice(root.length + 1);
            const tag = lite.has(rel) ? ' `[lite]`' : declared.has(rel) ? ' `[declared]`' : '';
            out.push(`- \`${rel}\`${tag}`);
        }
        out.push('');
    }
    return out.join('\n');
};

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
    const check = process.argv.includes('--check');
    const next = await render();
    const cur = await readFile(path.join(ROOT, OUT), 'utf8').catch(() => null);
    if (cur === next) { console.log(`${OUT} is current.`); }
    else if (check) {
        console.error(`${OUT} is STALE — run: node scripts/gen-vendored-files.mjs`);
        process.exit(1);
    } else {
        await writeFile(path.join(ROOT, OUT), next);
        console.log(`wrote ${OUT}`);
    }
}
