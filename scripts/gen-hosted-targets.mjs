#!/usr/bin/env node
/**
 * Generate docs/generated/hosted-targets.json from a stc-compiler checkout.
 *
 * The matrix's hosted facts (which chips stc-compiler will COMPILE C for, which
 * it will ASSEMBLE) are checked by test/bw-matrix-conformance.test.mjs against
 * this file. It used to be a hand-read snapshot; this derives it, so the day the
 * service owner deploys a new target the snapshot goes stale and the conformance
 * gate names the cell that is now wrong. Plan: docs/LANGUAGE-DEVICE-MATRIX-PLAN.md, T2.
 *
 * The target lists are the KEYS of five dicts in app.py — TARGETS (8051),
 * AVR_TARGETS, ARM_TARGETS, EATER_TARGETS (6502), and ASSEMBLE_TARGETS (target
 * -> family). Those keys are parsed with Python's own `ast`, not a regex over
 * the file: if the shape this relies on is gone (a dict renamed, no longer a
 * literal), we refuse BY NAME rather than emit a guess.
 *
 * The `$schema`, `service`, `other` and `absent` blocks are hand-maintained
 * notes, carried forward from the committed file unchanged — `absent` in
 * particular is a human's reading of what is deliberately NOT hosted and why.
 *
 * Usage:
 *   node scripts/gen-hosted-targets.mjs --dir /path/to/stc-compiler
 *   node scripts/gen-hosted-targets.mjs --dir /path/to/stc-compiler --check
 */
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const root = path.resolve(import.meta.dirname, '..');
const output = path.join(root, 'docs/generated/hosted-targets.json');
const rel = p => path.relative(root, p).replaceAll(path.sep, '/');

// The five dicts, and how each maps into the document.
const COMPILE_DICTS = {'8051': 'TARGETS', avr: 'AVR_TARGETS', arm: 'ARM_TARGETS', '6502': 'EATER_TARGETS'};
const ASSEMBLE_DICT = 'ASSEMBLE_TARGETS';
const REQUIRED = [...Object.values(COMPILE_DICTS), ASSEMBLE_DICT];

const HOW = 'generated by scripts/gen-hosted-targets.mjs from app.py '
    + 'TARGETS/AVR_TARGETS/ARM_TARGETS/EATER_TARGETS/ASSEMBLE_TARGETS (dict keys, parsed with '
    + "Python ast); refresh with `node scripts/gen-hosted-targets.mjs --dir <stc-compiler>`";

/** Parse the named dicts out of app.py with Python's ast — no execution, no
 *  regex-over-the-file. Returns {NAME: {keys:[...], values:[...]|null}}. */
function extractDicts (appPy, names) {
    const script = [
        'import ast, json, sys',
        'tree = ast.parse(open(sys.argv[1]).read())',
        'want = set(sys.argv[2:])',
        'out = {}',
        'for node in ast.walk(tree):',
        '    if isinstance(node, ast.Assign):',
        '        for t in node.targets:',
        '            if isinstance(t, ast.Name) and t.id in want and isinstance(node.value, ast.Dict):',
        '                keys, vals = [], []',
        '                for k, v in zip(node.value.keys, node.value.values):',
        '                    if isinstance(k, ast.Constant) and isinstance(k.value, str):',
        '                        keys.append(k.value)',
        '                        vals.append(v.value if isinstance(v, ast.Constant) and isinstance(v.value, str) else None)',
        '                out[t.id] = {"keys": keys, "values": vals if all(x is not None for x in vals) else None}',
        'print(json.dumps(out))'
    ].join('\n');
    let raw;
    try {
        raw = execFileSync('python3', ['-c', script, appPy, ...names], {encoding: 'utf8'});
    } catch (e) {
        throw new Error(`could not parse ${rel(appPy)} with python3 ast: ${e.message}`);
    }
    return JSON.parse(raw);
}

function shaOf (dir) {
    return execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], {encoding: 'utf8'}).trim();
}

/** Build the document from a checkout. `date` stamps source (today on a real
 *  refresh; the committed date on --check, so an unchanged file does not drift). */
function build (dir, date) {
    const appPy = path.join(dir, 'app.py');
    if (!fs.existsSync(appPy)) throw new Error(`no app.py under ${dir} — is that a stc-compiler checkout?`);
    const dicts = extractDicts(appPy, REQUIRED);
    for (const name of REQUIRED) {
        if (!dicts[name] || !dicts[name].keys.length) {
            throw new Error(`app.py has no usable ${name} dict — its shape changed; refusing to guess (plan T2)`);
        }
    }
    if (!dicts[ASSEMBLE_DICT].values) {
        throw new Error(`${ASSEMBLE_DICT} is no longer a flat target->family map; refusing to guess (plan T2)`);
    }

    const compile = {};
    for (const [family, dictName] of Object.entries(COMPILE_DICTS)) compile[family] = dicts[dictName].keys;

    // assemble: group ASSEMBLE_TARGETS keys by their family value, families in
    // first-appearance order.
    const assemble = {};
    const {keys, values} = dicts[ASSEMBLE_DICT];
    for (let i = 0; i < keys.length; i++) {
        (assemble[values[i]] ||= []).push(keys[i]);
    }

    // Hand-maintained notes, carried from the committed file.
    const prev = fs.existsSync(output) ? JSON.parse(fs.readFileSync(output, 'utf8')) : {};

    return {
        $schema: 'hosted-targets/v1',
        source: {
            repo: (prev.source && prev.source.repo) || 'https://github.com/CrispStrobe/stc-compiler',
            sha: shaOf(dir),
            generated: date,
            how: HOW
        },
        service: prev.service || 'https://stc-compiler.vercel.app',
        compile,
        assemble,
        other: prev.other || {},
        absent: prev.absent || {}
    };
}

const render = obj => JSON.stringify(obj, null, 2) + '\n';

function checkAgainst (dir) {
    const prev = fs.existsSync(output) ? JSON.parse(fs.readFileSync(output, 'utf8')) : {};
    // Carry the committed date so an unchanged file does not report stale merely
    // because a day passed; the sha and the target lists are what "stale" means.
    const date = (prev.source && prev.source.generated) || '';
    const expected = render(build(dir, date));
    const actual = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
    if (actual !== expected) {
        throw new Error(`${rel(output)} is stale against the stc-compiler checkout at ${dir} `
            + `(HEAD ${shaOf(dir).slice(0, 8)}); run: node scripts/gen-hosted-targets.mjs --dir ${dir}`);
    }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const args = process.argv.slice(2);
    const dirIdx = args.indexOf('--dir');
    const dir = dirIdx !== -1 ? path.resolve(args[dirIdx + 1]) : null;
    if (!dir) { console.error('usage: gen-hosted-targets.mjs --dir <stc-compiler checkout> [--check]'); process.exit(2); }
    if (args.includes('--check')) {
        checkAgainst(dir);
        console.log(`${rel(output)} is current against ${dir}`);
    } else {
        const today = new Date().toISOString().slice(0, 10);
        fs.mkdirSync(path.dirname(output), {recursive: true});
        fs.writeFileSync(output, render(build(dir, today)));
        console.log(`wrote ${rel(output)} from ${dir} (HEAD ${shaOf(dir).slice(0, 8)})`);
    }
}

export {build, render, checkAgainst, extractDicts, output};
