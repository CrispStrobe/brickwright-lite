/**
 * Regenerate adapter-wrapped built-ins from immutable authoritative sources.
 *
 * Usage:
 *   node scripts/sync-bundled-extensions.mjs
 *   node scripts/sync-bundled-extensions.mjs --check
 *
 * The generated overlay is deliberately not an editing surface. Change the
 * source repository, review and advance bundled-extension-pins.json, then run
 * this script.
 */
import {readFile, writeFile} from 'node:fs/promises';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pinsPath = resolve(root, 'bundled-extension-pins.json');
const pins = JSON.parse(await readFile(pinsPath, 'utf8'));
const check = process.argv.includes('--check');
const fullSha = /^[0-9a-f]{40}$/;
let stale = false;

for (const [name, pin] of Object.entries(pins)) {
    if (!fullSha.test(pin.commit)) throw new Error(`${name}: commit must be a full 40-hex SHA`);
    for (const key of ['repo', 'source', 'overlay']) {
        if (typeof pin[key] !== 'string' || !pin[key]) throw new Error(`${name}: missing ${key}`);
    }
    const url = `https://raw.githubusercontent.com/${pin.repo}/${pin.commit}/${pin.source}`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${name}: ${url} returned HTTP ${response.status}`);
    const source = await response.text();
    const provenance = `// Generated by scripts/sync-bundled-extensions.mjs from ${pin.repo}@${pin.commit}:${pin.source}.\n`;
    const generated = `${provenance}const makeExt = require("../adapter");\nmodule.exports = makeExt(${JSON.stringify(source)});\n`;
    const output = resolve(root, pin.overlay);
    const current = await readFile(output, 'utf8').catch(() => '');
    if (current === generated) continue;
    stale = true;
    if (!check) await writeFile(output, generated);
    console.error(`${check ? 'stale' : 'updated'}: ${pin.overlay}`);
}

if (check && stale) process.exitCode = 1;
