// Vendor every mapped extension from CrispStrobe/extensions at the pin, and
// record what was vendored.
//
// This is the whole of "Lite consumes from the pin". One command fetches the
// files the map claims, writes each as a bundle, and records the sha256 the
// offline gate then judges the tree against
// (test/bundled-extensions-match-upstream.test.mjs).
//
// WHY ONE SCRIPT AND NOT TWO
// --------------------------
// Vendoring and pinning were briefly separate — a build step that rendered a
// local source into a bundle, and a pin step that hashed upstream. That
// arrangement has a gap exactly the width of the problem it was meant to
// solve: the bundle could be rebuilt from the local source without the pin
// moving, which is a fork that passes its own check. Fetching and recording in
// one step means the bytes that land and the bytes that are pinned are the
// same bytes, because they are the same fetch.
//
// WHERE THE SOURCE LIVES NOW
// --------------------------
// Upstream. `spikeprime/source.js` used to be the readable copy Lite edited,
// with the bundle generated from it — the reverse of the rule, and the shape
// that produced eight forks. A change to a SPIKE block is made in
// CrispStrobe/extensions, and arrives here by moving UPSTREAM_COMMIT and
// running this.
//
// Fetched sha-addressed from raw.githubusercontent, which is immutable, so no
// cache can substitute for what the commit contains. Same doctrine as
// scripts/lib-pin.mjs and docs/FETCH-PINNING.md.
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {readFileSync} from 'node:fs';
import {MAP, UPSTREAM_COMMIT, UPSTREAM_REPO, ROOT, sha256, rawURL, bundlePath, sourceOf} from './bundled-upstream.mjs';

const PINS = resolve(ROOT, 'overlay/scratch-vm/src/extension-support/bundled-upstream-pins.json');

/**
 * The exact bytes a bundle must hold for a given extension source.
 *
 * The JSON-string form, deliberately. The template-literal form
 * (makeExt(`…`)) ended early on a stray backtick twice — 711e4744f and
 * 2258847c1, both filed as urgent build breaks — because a backtick anywhere
 * in a comment closes it. A JSON string has no such edge.
 */
export const renderBundle = source =>
    `const makeExt = require('../adapter');\nmodule.exports = makeExt(${JSON.stringify(source)});\n`;

const fetchText = async function (url, attempts = 3) {
    let lastError = null;
    for (let i = 0; i < attempts; i++) {
        try {
            const response = await fetch(url);
            if (!response.ok) throw new Error(`HTTP ${response.status}`);
            const text = await response.text();
            // A truncated body that still parsed would be vendored and pinned
            // together, and agree with itself forever.
            if (text.length < 500) throw new Error(`only ${text.length} bytes — truncated?`);
            return text;
        } catch (error) {
            lastError = error;
            await new Promise(r => setTimeout(r, 500 * (i + 1)));
        }
    }
    throw new Error(`${url}: ${lastError && lastError.message}`);
};

const check = process.argv.includes('--check');

const pins = {
    _comment: 'GENERATED by scripts/spike/vendor-bundles.mjs — do not hand-edit. sha256 of ' +
        'each upstream extension file at the recorded commit, taken from the same fetch that ' +
        'wrote the bundle beside it. test/bundled-extensions-match-upstream.test.mjs judges ' +
        'the tree against these, offline. Editing a hash to make that test pass is the one ' +
        'thing this file exists to make visible.',
    repo: UPSTREAM_REPO,
    commit: UPSTREAM_COMMIT,
    files: {}
};

let changed = 0;
const vendorPins = JSON.parse(readFileSync(resolve(ROOT, 'vendor-pins.json'), 'utf8'));

for (const id of Object.keys(MAP)) {
    const from = sourceOf(id, vendorPins);
    const source = await fetchText(rawURL(from.path, from.repo, from.commit));
    const bundle = renderBundle(source);
    pins.files[id] = {
        path: from.path,
        sha256: sha256(source),
        bytes: Buffer.byteLength(source, 'utf8'),
        // Recorded per file, because not every bundle comes from the same
        // repository: controller is vendored from the bw-board package, which
        // ships the extension and is pinned by sha like any other package.
        ...(from.repo === UPSTREAM_REPO ? {} : {repo: from.repo, commit: from.commit})
    };

    if (!check) {
        writeFileSync(bundlePath(id), bundle);
        changed++;
    }
    process.stderr.write(
        `${id.padEnd(20)} ${pins.files[id].sha256.slice(0, 16)}  ${pins.files[id].bytes} B` +
        `${from.repo === UPSTREAM_REPO ? '' : `  <- ${from.repo}`}\n`);
}

if (check) {
    process.stderr.write('\n--check: nothing written\n');
} else {
    writeFileSync(PINS, `${JSON.stringify(pins, null, 4)}\n`);
    process.stderr.write(`\nvendored ${changed} bundle(s) at ${UPSTREAM_COMMIT.slice(0, 8)} and wrote ${PINS}\n`);
}
